import { useJournal } from '../../store'
import { useConfirm } from '../ConfirmDialog'
import { notify } from '../../lib/notify'
import { todayISO } from '../../lib/date'
import { emptyJournal } from '../../lib/storage'
import { generateDemoData } from '../../lib/demo'
import { downloadBackup } from './download'
import { eraseDevice, wipeableKeys, wipeSummary } from '../../lib/wipe'
import { signOut } from '../../lib/supabase'
import { Cells, ToggleCell } from '../ui/cells'

/**
 * Sample data, and the danger zone. The only card in Settings that can destroy
 * a journal, which is why every button here routes through `confirm` with an
 * `onBackup` offer — except "Remove demo data", deliberately: the samples are
 * generated from a fixed seed in `lib/demo.ts`, so offering to download a copy
 * would imply they are yours and worth keeping.
 */
export function DemoResetCard() {
  const confirm = useConfirm()
  const { data, setSettings, replaceAll } = useJournal()

  async function doExport() {
    await downloadBackup(data)
    setSettings({ lastBackup: todayISO() })
  }

  async function loadDemo() {
    if (data.entries.length === 0 || await confirm({
      title: 'Load demo data?',
      description: 'This replaces your current journal with about 30 days of sample entries.',
      confirmLabel: 'Load demo data', destructive: true, onBackup: doExport,
    })) {
      replaceAll(generateDemoData())
    }
  }

  async function removeDemo() {
    if (await confirm({
      title: 'Remove the demo data?',
      description: `This journal was filled with samples. Removing them clears all ${data.entries.length} entries and starts you on an empty journal — including anything you have added since.`,
      // No `onBackup`, unlike every other destructive action here.
      // Demo data is generated by `lib/demo.ts` from a fixed seed —
      // it is in the code, reproducible on demand, and identical for
      // everyone. Offering to download a copy of it implies it is
      // yours and worth keeping, which is the opposite of what this
      // button is for.
      confirmLabel: 'Remove the samples', destructive: true,
    })) {
      replaceAll(emptyJournal())
      setSettings({ storageMode: 'local', demoSeeded: false, explore: false })
      notify.success('Demo data removed', 'You are starting from an empty journal.')
    }
  }

  async function eraseAll() {
    if (await confirm({
      title: 'Erase everything and start fresh?',
      // The count is named because it is the thing being destroyed,
      // and the three credentials are named because they are the
      // things a user assumes are gone and, until COD-299, were not.
      description: `This deletes all ${data.entries.length} entries, ${data.habits.length} habits, ${data.workouts.length} workouts and every photo — and it signs you out, forgets your sync passphrase, and clears the ${wipeableKeys().length} items this app has stored in this browser. It cannot be undone.`,
      confirmLabel: 'Erase everything', destructive: true, onBackup: doExport,
    })) {
      // Order matters. `signOut` first, while the session token is
      // still present: revoking it server-side needs the refresh
      // token that `eraseDevice` is about to delete, and a local-only
      // wipe would leave a live session on Supabase's side.
      try { await signOut() } catch { /* offline: the local key still goes below */ }
      const report = await eraseDevice()
      // Empty the in-memory journal LAST. `replaceAll` persists, so
      // doing it first would write `bujo:data` straight back after
      // the sweep had removed it.
      replaceAll(emptyJournal())
      notify.success('Erased', wipeSummary(report))
    }
  }

  async function toStart() {
    if (await confirm({
      title: 'Return to the start screen?',
      description: 'Your data is kept, and you can choose guest, account, or device again.',
      confirmLabel: 'Go to start screen',
    })) setSettings({ storageMode: undefined })
  }

  async function setAllowed(on: boolean) {
    setSettings({ demoDisabled: !on })
    if (on) {
      notify.success('Demo data allowed', 'You can load the sample journal again.')
      return
    }
    // Switching it off only stopped *future* seeding, which is not
    // what "disable demo data" means to someone looking at a journal
    // full of samples. If this journal is the samples, offer to clear
    // them in the same gesture rather than leaving the switch looking
    // like it did nothing.
    if (!data.settings.demoSeeded) {
      notify.success('Demo data switched off', 'Sample data can no longer be loaded.')
      return
    }
    if (await confirm({
      title: 'Clear the samples already loaded?',
      description: `New samples can no longer load. This journal is still holding ${data.entries.length} of them — clearing now starts you on an empty journal, including anything you have added since.`,
      confirmLabel: 'Clear them now',
      cancelLabel: 'Keep them for now',
      destructive: true,
    })) {
      replaceAll(emptyJournal())
      setSettings({ storageMode: 'local', demoSeeded: false, explore: false, demoDisabled: true })
      notify.success('Demo data removed', 'You are starting from an empty journal.')
    } else {
      notify.info('Demo data switched off', 'The samples already here are untouched; you can remove them any time.')
    }
  }

  // One row per action, iOS style, the destructive one last and red. Every
  // handler above asks first and names what it removes. "Load demo data" is
  // hidden, not disabled, when demo is switched off — the toggle answers why;
  // "Remove demo data" exists only while the journal IS the samples.
  return (
    <Cells title="Demo & reset">
      <ToggleCell title="Allow demo data" subtitle="Off: ?demo=1 links are ignored" on={!data.settings.demoDisabled} onChange={setAllowed} />
      {!data.settings.demoDisabled && <button type="button" className="cell cell-action" onClick={loadDemo}>Load demo data</button>}
      {data.settings.demoSeeded && <button type="button" className="cell cell-action" onClick={removeDemo}>Remove demo data</button>}
      <button type="button" className="cell cell-action" onClick={toStart}>Back to start screen</button>
      <button type="button" className="cell cell-danger" onClick={eraseAll}>Clear all data</button>
    </Cells>
  )

}
